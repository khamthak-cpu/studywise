import asyncio
import logging
from typing import Any

import chromadb
from chromadb.errors import NotFoundError
from ollama import AsyncClient

from app.config import Settings
from app.schemas import Source

log = logging.getLogger(__name__)


class Retriever:
    """
    Retrieves relevant NCERT textbook chunks from ChromaDB.

    Expected metadata:
        chapter: str
        section: str | None
        page: int | None
        subject: str  (lowercase)
        class_level: int

    The collection should use cosine distance and contain
    documents with embeddings generated by the configured
    Ollama embedding model.
    """

    def __init__(self, settings: Settings, ollama: AsyncClient):
        self._s = settings
        self._ollama = ollama
        self._col = None
        self._client = None

        try:
            self._client = chromadb.PersistentClient(
                path=str(settings.chroma_path)
            )

            self._col = self._client.get_collection(
                name=settings.collection
            )

            count = self._col.count()

            if count > 0:
                log.info(
                    "NCERT index loaded: %d chunks from collection '%s'",
                    count,
                    settings.collection,
                )
            else:
                log.warning(
                    "Collection '%s' exists but contains no chunks.",
                    settings.collection,
                )

        except NotFoundError:
            log.warning(
                "Collection '%s' does not exist at %s. "
                "Run the ingestion/indexing script first.",
                settings.collection,
                settings.chroma_path,
            )
        except Exception:
            log.exception(
                "Could not load ChromaDB collection '%s'.",
                settings.collection,
            )

    @property
    def ready(self) -> bool:
        """Return True only when a usable index contains documents."""
        try:
            return self._col is not None and self._col.count() > 0
        except Exception:
            log.exception("Could not check the index status.")
            return False

    def count(self) -> int:
        """Return the number of indexed textbook chunks."""
        if self._col is None:
            return 0

        try:
            return self._col.count()
        except Exception:
            log.exception("Could not count indexed chunks.")
            return 0

    async def _embed(self, text: str) -> list[float]:
        """Generate an embedding using the configured Ollama model."""
        text = text.strip()

        if not text:
            raise ValueError("Cannot embed an empty query.")

        response = await self._ollama.embed(
            model=self._s.embed_model,
            input=text,
        )

        if not response.embeddings or not response.embeddings[0]:
            raise RuntimeError(
                f"Ollama model '{self._s.embed_model}' "
                "returned an empty embedding."
            )

        return response.embeddings[0]

    @staticmethod
    def _where(
        class_level: int | None,
        subject: str | None,
    ) -> dict[str, Any] | None:
        """Build ChromaDB metadata filters."""
        conditions = []

        if class_level is not None:
            conditions.append({"class_level": int(class_level)})

        if subject:
            normalized_subject = subject.strip().lower()
            if normalized_subject:
                conditions.append({"subject": normalized_subject})

        if not conditions:
            return None

        if len(conditions) == 1:
            return conditions[0]

        return {"$and": conditions}

    async def search(
        self,
        query: str,
        class_level: int | None = None,
        subject: str | None = None,
    ) -> list[Source]:
        """
        Search the NCERT index and return the most relevant sources.

        Returns an empty list when the index is unavailable or
        no matching documents exist.
        """
        if not self.ready:
            log.warning("NCERT index is not ready; returning no sources.")
            return []

        query = query.strip()

        if not query:
            return []

        try:
            embedding = await self._embed(query)

            where = self._where(class_level, subject)

            query_kwargs: dict[str, Any] = {
                "query_embeddings": [embedding],
                "n_results": min(
                    max(1, int(self._s.top_k)),
                    self.count(),
                ),
                "include": [
                    "documents",
                    "metadatas",
                    "distances",
                ],
            }

            if where is not None:
                query_kwargs["where"] = where

            result = await asyncio.to_thread(
                self._col.query,
                **query_kwargs,
            )

            documents = (result.get("documents") or [[]])[0] or []
            metadatas = (result.get("metadatas") or [[]])[0] or []
            distances = (result.get("distances") or [[]])[0] or []

            sources: list[Source] = []

            for document, metadata, distance in zip(
                documents,
                metadatas,
                distances,
            ):
                if not document:
                    continue

                metadata = metadata or {}

                # Cosine distance ranges from 0 to 2; clamp similarity to [0, 1].
                similarity = max(0.0, min(1.0, 1.0 - float(distance)))

                page_value = metadata.get("page")
                try:
                    page_value = (
                        int(page_value)
                        if page_value is not None
                        else None
                    )
                except (TypeError, ValueError):
                    page_value = None

                sources.append(
                    Source(
                        title=str(
                            metadata.get(
                                "chapter",
                                metadata.get("source", "NCERT"),
                            )
                        ),
                        section=metadata.get("section"),
                        page=page_value,
                        score=round(similarity, 4),
                        snippet=" ".join(document.split())[:200],
                        text=document,
                    )
                )

            return sources

        except Exception:
            log.exception("NCERT retrieval failed.")
            return []