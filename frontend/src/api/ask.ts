import type { AskRequest, AskResponse, UploadedAttachment } from "../types";

const API_URL = (import.meta.env.VITE_API_URL as string | undefined) ?? "http://localhost:8000";
const USE_MOCK = (import.meta.env.VITE_USE_MOCK as string | undefined) === "true";

const wait = (ms: number) => new Promise((resolve) => window.setTimeout(resolve, ms));

function makeMockResponse(request: AskRequest): AskResponse {
  const simplified = request.mode === "simplify";
  const q = request.question.toLowerCase();
  let answer: string;
  let chapter = "Study Guide";
  let page = 12;
  let title = "Sample Textbook";

  if (q.includes("tcp") || q.includes("udp")) {
    answer = simplified
      ? "TCP is like sending a tracked parcel: it checks that the data arrives correctly and in order. UDP is more like sending a quick announcement: it is faster and has less overhead, but it does not guarantee delivery."
      : "TCP (Transmission Control Protocol) is connection-oriented and provides reliable, ordered delivery of data. UDP (User Datagram Protocol) is connectionless and has lower overhead, but it does not guarantee delivery or ordering. Applications choose between them based on whether reliability or low latency matters more.";
    chapter = "Transport Layer";
    page = 42;
    title = "Computer Networks";
  } else if (q.includes("rag") || q.includes("retrieval")) {
    answer = "Retrieval-Augmented Generation (RAG) first retrieves relevant passages from a knowledge source, then gives those passages to a language model as context for its answer. In this prototype, RAG can retrieve textbook chunks from ChromaDB and pass them to a locally running Ollama model. This sample answer is illustrative; it was not retrieved from your actual textbook library.";
    chapter = "AI System Design";
    page = 8;
    title = "AI Study Assistant Notes";
  } else {
    answer = `Here is a sample response to “${request.question}”. When your FastAPI backend is connected, this area will show an answer generated by your local AI model using relevant textbook passages. The current demo uses mock data and does not search your real textbooks.`;
  }

  return {
    answer,
    confidence: q.includes("unknown-topic-xyz") ? "uncertain" : "grounded",
    sources: [{ title, chapter, page, excerpt: "Sample citation for layout testing only. Connect the backend to receive real retrieved passages." }],
    mode: "offline"
  };
}

export async function askQuestion(request: AskRequest): Promise<AskResponse> {
  if (USE_MOCK) {
    await wait(850);
    return makeMockResponse(request);
  }

  const controller = new AbortController();
  const timeout = window.setTimeout(() => controller.abort(), 120_000);
  let response: Response;
  try {
    response = await fetch(`${API_URL}/ask`, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        question: request.question,
        conversation_id: request.conversationId,
        student_id: request.studentId ?? "demo-student",
        attachment_ids: request.attachmentIds ?? [],
        language: request.language,
        simplify: request.mode === "simplify",
        mode: "auto"
      }),
      signal: controller.signal
    });
  } catch (error) {
    if (error instanceof DOMException && error.name === "AbortError") {
      throw new Error("The study server took too long to respond. Check Ollama and try again.");
    }
    throw new Error("Cannot reach the study server. Check that the backend is running and VITE_API_URL is correct.");
  } finally {
    window.clearTimeout(timeout);
  }

  if (!response.ok) {
    const detail = await response.text().catch(() => "");
    throw new Error(detail || `The study server returned ${response.status}.`);
  }

  const data = await response.json() as {
    answer: string;
    sources?: Array<{ title: string; section?: string | null; page?: number | null; url?: string | null; snippet?: string; score?: number | null }>;
    confidence?: number;
    answered_from?: "notes" | "web" | "fallback";
    language?: "en" | "hi";
    online?: boolean;
    latency_ms?: number;
  };
  return {
    answer: data.answer,
    confidence: typeof data.confidence === "number" && data.confidence >= 0.45 && data.answered_from !== "fallback" ? "grounded" : "uncertain",
    confidenceScore: data.confidence,
    sources: (data.sources ?? []).map((source) => ({
      title: source.title,
      section: source.section ?? undefined,
      chapter: source.section ?? undefined,
      page: source.page ?? undefined,
      excerpt: source.snippet,
      snippet: source.snippet,
      url: source.url ?? undefined
    })),
    mode: data.answered_from === "web" ? "online" : "offline",
    answeredFrom: data.answered_from,
    language: data.language,
    latencyMs: data.latency_ms
  };
}

export async function createConversation(title = "New chat"): Promise<{ id: number; title: string }> {
  const response = await fetch(`${API_URL}/history/conversations`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ student_id: "demo-student", title })
  });
  if (!response.ok) throw new Error("Could not start a new conversation.");
  return await response.json() as { id: number; title: string };
}

export async function uploadAttachment(file: File, conversationId: number): Promise<UploadedAttachment> {
  const form = new FormData();
  form.append("file", file);
  form.append("conversation_id", String(conversationId));
  form.append("student_id", "demo-student");
  const response = await fetch(`${API_URL}/uploads`, { method: "POST", body: form });
  if (!response.ok) {
    let detail = `Upload failed (${response.status}).`;
    try {
      const data = await response.json() as { detail?: string };
      if (data.detail) detail = data.detail;
    } catch { /* use fallback message */ }
    throw new Error(detail);
  }
  return await response.json() as UploadedAttachment;
}

export async function checkHealth(): Promise<{
  status?: string;
  model_available?: boolean;
  knowledge_base_ready?: boolean;
  online?: boolean;
}> {
  const controller = new AbortController();
  const timeout = window.setTimeout(() => controller.abort(), 5000);
  let response: Response;
  try {
    response = await fetch(`${API_URL}/health`, { method: "GET", signal: controller.signal });
  } catch {
    throw new Error("Study server is unavailable. Start the backend and check VITE_API_URL.");
  } finally {
    window.clearTimeout(timeout);
  }
  if (!response.ok) {
    throw new Error("Study server is unavailable.");
  }
  const data = await response.json() as {
    status?: string;
    online?: boolean;
    llm_model?: { ready?: boolean };
    embed_model?: { ready?: boolean };
    index?: { ready?: boolean };
  };
  return {
    status: data.status,
    online: data.online,
    model_available: Boolean(data.llm_model?.ready && data.embed_model?.ready),
    knowledge_base_ready: Boolean(data.index?.ready)
  };
}

